#!/usr/bin/env python3
"""Throwaway HOME for Portico performance measurements (never touches the real ~/.ssh).

Creates  <root>/home/.ssh/config  (+ conf.d/*.conf via Include), known_hosts, a test key,
and empty XDG dirs, so that `HOME=<root>/home XDG_CONFIG_HOME=... portico` sees only this.

  python3 bench/fixtures.py <root> --hosts 50 --includes 3 [--sshd-port N --hostkey FILE.pub]

Hosts named `local-1..local-5` point at 127.0.0.1:<sshd-port> (the throwaway sshd of perf.py).
"""
import argparse
import os
import subprocess
from pathlib import Path

ENVS = ["prod", "staging", "dev", "lab"]
ROLES = ["web", "api", "db", "cache", "queue", "worker", "edge", "metrics"]


def host_block(i: int) -> str:
    env = ENVS[i % len(ENVS)]
    role = ROLES[i % len(ROLES)]
    alias = f"{role}-{env}-{i:04d}"
    lines = [f"Host {alias}",
             f"  HostName {role}{i}.{env}.example.internal",
             f"  User {'deploy' if env == 'prod' else 'ops'}"]
    if i % 3 == 0:
        lines.append(f"  Port {2200 + i % 50}")
    if env == "prod":
        lines.append("  ProxyJump bastion-prod")
    elif i % 5 == 0:
        lines.append("  ProxyJump bastion-lab,bastion-prod")
    if i % 7 == 0:
        lines.append("  LocalForward 15432 localhost:5432")
    if i % 4 == 1:
        lines.append("  IdentityFile ~/.ssh/id_%r_ed25519")
    return "\n".join(lines) + "\n"


def write(root: Path, hosts: int, includes: int, sshd_port: int | None, hostkey: str | None,
          alive: int = 60) -> None:
    home = root / "home"
    ssh = home / ".ssh"
    confd = ssh / "conf.d"
    confd.mkdir(parents=True, exist_ok=True)
    for x in ("config", "local/share", "local/state", "cache"):
        (root / "xdg" / x).mkdir(parents=True, exist_ok=True)
    os.chmod(ssh, 0o700)

    head = [
        "# throwaway config generated by bench/fixtures.py",
        f"Include conf.d/*.conf",
        "",
        "Host bastion-prod",
        "  HostName bastion.prod.example.internal",
        "  User jump",
        "",
        "Host bastion-lab",
        "  HostName bastion.lab.example.internal",
        "",
    ]
    if sshd_port:
        for k in range(1, 6):
            head += [f"Host local-{k}",
                     "  HostName 127.0.0.1",
                     f"  Port {sshd_port}",
                     f"  User {os.environ.get('USER', 'root')}",
                     f"  IdentityFile {ssh}/id_ed25519",
                     "  IdentitiesOnly yes",
                     ""]
    # Body split: a share in the main file, the rest spread across includes.
    per_file: list[list[str]] = [[] for _ in range(includes + 1)]
    for i in range(hosts):
        per_file[i % (includes + 1)].append(host_block(i))
    tail = [
        "",
        "Match host *.prod.example.internal user deploy",
        "  ServerAliveInterval 30",
        "",
        "Host *.lab.example.internal",
        "  StrictHostKeyChecking yes",
        "",
        "Host *",
        f"  ServerAliveInterval {alive}",
        "  AddKeysToAgent yes",
        "",
    ]
    (ssh / "config").write_text("\n".join(head) + "\n" + "\n".join(per_file[0]) + "\n".join(tail))
    for n in range(includes):
        (confd / f"{n:02d}-fleet.conf").write_text("\n".join(per_file[n + 1]))
    key = ssh / "id_ed25519"
    if not key.exists():
        subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "portico-bench", "-f", str(key)],
                       check=True)
    kh = ssh / "known_hosts"
    kh.write_text(f"[127.0.0.1]:{sshd_port} {Path(hostkey).read_text().split()[0]} "
                  f"{Path(hostkey).read_text().split()[1]}\n" if (sshd_port and hostkey) else "")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("root", type=Path)
    p.add_argument("--hosts", type=int, default=50)
    p.add_argument("--includes", type=int, default=3)
    p.add_argument("--sshd-port", type=int)
    p.add_argument("--hostkey")
    p.add_argument("--alive", type=int, default=60, help="ServerAliveInterval of `Host *`")
    a = p.parse_args()
    write(a.root, a.hosts, a.includes, a.sshd_port, a.hostkey, a.alive)
