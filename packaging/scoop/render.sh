#!/usr/bin/env bash
# Render the Scoop manifest (bucket/portico.json, the TUI) for a published
# Portico release, from the template next to this script and the release's
# SHA256SUMS. Needs bash, awk, sed and grep only.
#
#   packaging/scoop/render.sh <version> <SHA256SUMS> [out-dir]
#
# <version>    X.Y.Z (no leading v, no pre-release: those never reach the bucket)
# <SHA256SUMS> the file attached to the GitHub Release
# [out-dir]    default: dist/scoop (gets bucket/portico.json, the bucket layout)
#
# Environment: PORTICO_REPO_URL (default https://github.com/fs0ciety7000/Portico).
# Exit status is non-zero, and nothing is written, if the Windows zip is
# missing from SHA256SUMS or its checksum is malformed.
set -euo pipefail

die() { printf 'render.sh: %s\n' "$*" >&2; exit 1; }

if [ $# -lt 2 ] || [ $# -gt 3 ]; then die "usage: $0 <version> <SHA256SUMS> [out-dir]"; fi
version=$1
sums=$2
out=${3:-dist/scoop}
repo_url=${PORTICO_REPO_URL:-https://github.com/fs0ciety7000/Portico}
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "version must be X.Y.Z, got '$version'"
[[ $repo_url =~ ^https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] \
  || die "PORTICO_REPO_URL must be https://github.com/<owner>/<repo>, got '$repo_url'"
[ -f "$sums" ] || die "no such file: $sums"

# sha_of <file name>: the checksum recorded for exactly that name (sha256sum
# format, text or binary mode marker).
sha_of() {
  local sha
  sha=$(awk -v f="$1" '{ n = $2; sub(/^\*/, "", n) } n == f { print $1 }' "$sums")
  [ -n "$sha" ] || die "$1 is not listed in $sums"
  [ "$(printf '%s\n' "$sha" | wc -l)" -eq 1 ] || die "$1 is listed more than once in $sums"
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || die "malformed SHA-256 for $1"
  printf '%s' "$sha"
}

sha_zip=$(sha_of "portico-$version-x86_64-pc-windows-msvc.zip")
header="Generated by packaging/scoop/render.sh for Portico $version. Do not edit: the release workflow overwrites this file (template: packaging/scoop/ in $repo_url)."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/bucket"
sed \
  -e "s|@HEADER@|$header|g" \
  -e "s|@VERSION@|$version|g" \
  -e "s|@REPO_URL@|$repo_url|g" \
  -e "s|@SHA_X86_64_PC_WINDOWS_MSVC@|$sha_zip|g" \
  "$here/portico.json" > "$tmp/bucket/portico.json"

if grep -n '@[A-Z0-9_]*@' "$tmp/bucket/portico.json"; then
  die "unreplaced placeholder (see above)"
fi

mkdir -p "$out/bucket"
cp "$tmp/bucket/portico.json" "$out/bucket/portico.json"
printf '%s\n' "$out/bucket/portico.json"
