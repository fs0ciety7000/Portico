#!/usr/bin/env bash
# Render the Homebrew tap files (Formula/portico.rb, Casks/portico.rb) for a
# published Portico release, from the templates next to this script and the
# release's SHA256SUMS. Needs bash, awk, sed and grep only.
#
#   packaging/homebrew/render.sh <version> <SHA256SUMS> [out-dir]
#
# <version>   X.Y.Z (no leading v, no pre-release: those never reach the tap)
# <SHA256SUMS> the file attached to the GitHub Release
# [out-dir]   default: dist/homebrew (gets Formula/ and Casks/, the tap layout)
#
# Environment: PORTICO_REPO_URL (default https://github.com/fs0ciety7000/Portico).
# Exit status is non-zero, and nothing is written, if an artifact is missing
# from SHA256SUMS or a checksum is malformed.
set -euo pipefail

die() { printf 'render.sh: %s\n' "$*" >&2; exit 1; }

if [ $# -lt 2 ] || [ $# -gt 3 ]; then die "usage: $0 <version> <SHA256SUMS> [out-dir]"; fi
version=$1
sums=$2
out=${3:-dist/homebrew}
repo_url=${PORTICO_REPO_URL:-https://github.com/fs0ciety7000/Portico}
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "version must be X.Y.Z, got '$version'"
[[ $repo_url =~ ^https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] \
  || die "PORTICO_REPO_URL must be https://github.com/<owner>/<repo>, got '$repo_url'"
[ -f "$sums" ] || die "no such file: $sums"

# sha_of <file name>: the checksum recorded for exactly that name (sha256sum
# format, text or binary mode marker).
sha_of() {
  local sha
  sha=$(awk -v f="$1" '{ n = $2; sub(/^\*/, "", n) } n == f { print $1 }' "$sums")
  [ -n "$sha" ] || die "$1 is not listed in $sums"
  [ "$(printf '%s\n' "$sha" | wc -l)" -eq 1 ] || die "$1 is listed more than once in $sums"
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || die "malformed SHA-256 for $1"
  printf '%s' "$sha"
}

tui_sha() { sha_of "portico-$version-$1.tar.gz"; }
sha_arm_mac=$(tui_sha aarch64-apple-darwin)
sha_intel_mac=$(tui_sha x86_64-apple-darwin)
sha_arm_linux=$(tui_sha aarch64-unknown-linux-gnu)
sha_intel_linux=$(tui_sha x86_64-unknown-linux-gnu)

# The release keeps exactly one dmg; its suffix says how it was signed
# (docs/RELEASE.md): none = notarized, -not-notarized, -unsigned.
dmg_suffix=
found=
for suffix in "" -not-notarized -unsigned; do
  if awk -v f="Portico_${version}_universal$suffix.dmg" \
      '{ n = $2; sub(/^\*/, "", n) } n == f { found = 1 } END { exit !found }' "$sums"; then
    dmg_suffix=$suffix
    found=yes
    break
  fi
done
[ -n "$found" ] || die "no Portico_${version}_universal*.dmg in $sums"
sha_dmg=$(sha_of "Portico_${version}_universal$dmg_suffix.dmg")

header="# Generated by packaging/homebrew/render.sh for Portico $version. Do not edit:
# the release workflow overwrites this file (template: packaging/homebrew/ in
# $repo_url)."

# render <template> <dest>: drop the template's leading comment, put the
# generated header instead, substitute the placeholders.
render() {
  {
    printf '%s\n' "$header"
    awk 'started || !/^#/ { started = 1; print }' "$1" | sed \
      -e "s|@VERSION@|$version|g" \
      -e "s|@REPO_URL@|$repo_url|g" \
      -e "s|@SHA_AARCH64_APPLE_DARWIN@|$sha_arm_mac|g" \
      -e "s|@SHA_X86_64_APPLE_DARWIN@|$sha_intel_mac|g" \
      -e "s|@SHA_AARCH64_UNKNOWN_LINUX_GNU@|$sha_arm_linux|g" \
      -e "s|@SHA_X86_64_UNKNOWN_LINUX_GNU@|$sha_intel_linux|g" \
      -e "s|@DMG_SUFFIX@|$dmg_suffix|g" \
      -e "s|@SHA_DMG@|$sha_dmg|g"
  } > "$2"
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/Formula" "$tmp/Casks"
render "$here/Formula/portico.rb" "$tmp/Formula/portico.rb"
render "$here/Casks/portico.rb" "$tmp/Casks/portico.rb.in"

# Caveats only for a dmg that Gatekeeper will not accept as is.
case $dmg_suffix in
  "") caveats_text= ;;
  -not-notarized) caveats_text="This build of Portico is signed but not notarized by Apple." ;;
  -unsigned) caveats_text="This build of Portico is neither signed nor notarized by Apple." ;;
esac
awk -v text="$caveats_text" '
  /^  # @CAVEATS@$/ {
    if (text != "") {
      print ""
      print "  caveats <<~EOS"
      print "    " text
      print "    Gatekeeper blocks its first launch: after checking the download against"
      print "    SHA256SUMS (see docs/RELEASE.md), allow it once in System Settings >"
      print "    Privacy & Security, or run:"
      print "      xattr -dr com.apple.quarantine \"#{appdir}/Portico.app\""
      print "  EOS"
    }
    next
  }
  { print }
' "$tmp/Casks/portico.rb.in" > "$tmp/Casks/portico.rb"
rm "$tmp/Casks/portico.rb.in"

if grep -n '@[A-Z0-9_]*@' "$tmp/Formula/portico.rb" "$tmp/Casks/portico.rb"; then
  die "unreplaced placeholder (see above)"
fi

mkdir -p "$out/Formula" "$out/Casks"
cp "$tmp/Formula/portico.rb" "$out/Formula/portico.rb"
cp "$tmp/Casks/portico.rb" "$out/Casks/portico.rb"
if [ -n "$dmg_suffix" ]; then
  printf 'render.sh: warning: the cask points to Portico_%s_universal%s.dmg (Gatekeeper caveat added)\n' \
    "$version" "$dmg_suffix" >&2
fi
printf '%s\n' "$out/Formula/portico.rb" "$out/Casks/portico.rb"
