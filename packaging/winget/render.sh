#!/usr/bin/env bash
# Render the winget manifests of a published Portico release (desktop app
# from the NSIS installer, terminal UI from the zip), from the templates next
# to this script and the release's SHA256SUMS, in the layout of
# microsoft/winget-pkgs, for a pull request opened by hand (docs/RELEASE.md,
# "Winget"). Needs bash, awk, sed and grep only.
#
#   packaging/winget/render.sh <version> <SHA256SUMS> [out-dir]
#
# <version>    X.Y.Z (no leading v, no pre-release)
# <SHA256SUMS> the file attached to the GitHub Release
# [out-dir]    default: dist/winget (gets manifests/<p>/<Publisher>/<Package>/<version>/)
#
# Environment:
#   PORTICO_REPO_URL  default https://github.com/fs0ciety7000/Portico
#   WINGET_PUBLISHER  first part of the package identifiers (default fs0ciety7000):
#                     <publisher>.Portico (desktop app), <publisher>.PorticoTUI
#   RELEASE_DATE      YYYY-MM-DD of the release (default: today, UTC)
# Exit status is non-zero, and nothing is written, if an artifact is missing
# from SHA256SUMS or a checksum is malformed.
set -euo pipefail

die() { printf 'render.sh: %s\n' "$*" >&2; exit 1; }

if [ $# -lt 2 ] || [ $# -gt 3 ]; then die "usage: $0 <version> <SHA256SUMS> [out-dir]"; fi
version=$1
sums=$2
out=${3:-dist/winget}
repo_url=${PORTICO_REPO_URL:-https://github.com/fs0ciety7000/Portico}
publisher=${WINGET_PUBLISHER:-fs0ciety7000}
release_date=${RELEASE_DATE:-$(date -u +%Y-%m-%d)}
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "version must be X.Y.Z, got '$version'"
[[ $repo_url =~ ^https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] \
  || die "PORTICO_REPO_URL must be https://github.com/<owner>/<repo>, got '$repo_url'"
# winget identifiers: segments of letters, digits, '-' and '_' (no dot here,
# the dot separates the publisher from the package).
[[ $publisher =~ ^[A-Za-z0-9][A-Za-z0-9_-]{0,31}$ ]] \
  || die "WINGET_PUBLISHER must be letters, digits, '-' or '_', got '$publisher'"
[[ $release_date =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || die "RELEASE_DATE must be YYYY-MM-DD, got '$release_date'"
[ -f "$sums" ] || die "no such file: $sums"

# sha_of <file name>: the checksum recorded for exactly that name (sha256sum
# format, text or binary mode marker), upper case as winget-pkgs writes it.
sha_of() {
  local sha
  sha=$(awk -v f="$1" '{ n = $2; sub(/^\*/, "", n) } n == f { print $1 }' "$sums")
  [ -n "$sha" ] || die "$1 is not listed in $sums"
  [ "$(printf '%s\n' "$sha" | wc -l)" -eq 1 ] || die "$1 is listed more than once in $sums"
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || die "malformed SHA-256 for $1"
  printf '%s' "$sha" | tr 'a-f' 'A-F'
}

sha_setup=$(sha_of "Portico_${version}_x64-setup.exe")
sha_zip=$(sha_of "portico-$version-x86_64-pc-windows-msvc.zip")
first=$(printf '%s' "${publisher:0:1}" | tr '[:upper:]' '[:lower:]')

header="# Generated by packaging/winget/render.sh for Portico $version (template:
# packaging/winget/ in $repo_url).
# Check with \`winget validate --manifest <folder>\` before the pull request."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# render <package> <kind> <dest>: drop the template's leading comment, put
# the generated header instead, substitute the placeholders.
render() {
  {
    printf '%s\n' "$header"
    awk 'started || !/^#/ { started = 1; print }' "$here/$1/$2.yaml" | sed \
      -e "s|@PACKAGE_ID@|$publisher.$1|g" \
      -e "s|@VERSION@|$version|g" \
      -e "s|@REPO_URL@|$repo_url|g" \
      -e "s|@RELEASE_DATE@|$release_date|g" \
      -e "s|@SHA_SETUP@|$sha_setup|g" \
      -e "s|@SHA_ZIP@|$sha_zip|g"
  } > "$3"
}

written=()
for package in Portico PorticoTUI; do
  rel="manifests/$first/$publisher/$package/$version"
  mkdir -p "$tmp/$rel"
  id="$publisher.$package"
  render "$package" version "$tmp/$rel/$id.yaml"
  render "$package" installer "$tmp/$rel/$id.installer.yaml"
  render "$package" locale.en-US "$tmp/$rel/$id.locale.en-US.yaml"
  written+=("$rel/$id.yaml" "$rel/$id.installer.yaml" "$rel/$id.locale.en-US.yaml")
done

if grep -rn '@[A-Z0-9_]*@' "$tmp/manifests"; then
  die "unreplaced placeholder (see above)"
fi

for f in "${written[@]}"; do
  mkdir -p "$out/$(dirname "$f")"
  cp "$tmp/$f" "$out/$f"
  printf '%s\n' "$out/$f"
done
